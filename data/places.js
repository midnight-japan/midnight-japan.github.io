export const PLACES = RAW.map(([name, kind, lat, lon]) => ({ name, kind, x: Math.round((lon - O.lon) * KX * 10) / 10, z: Math.round(-(lat - O.lat) * KZ * 10) / 10 }));
// nearest land place (not water/JCT) within `max` metres
export function placeAt(x, z, max = 1600) {
  let best = null, bd = max * max;
  for (const p of PLACES) { if (p.kind === 'water' || p.kind === 'jct') continue; const d = (p.x - x) ** 2 + (p.z - z) ** 2; if (d < bd) { bd = d; best = p; } }
  return best;
}
